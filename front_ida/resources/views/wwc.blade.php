                                Le Forum Mondial de l'Eau est le plus grand événement lié à l'eau au monde et est organisé par le Conseil Mondial de l'Eau (WWC), une organisation internationale qui rassemble tous ceux qui s'intéressent au thème de l'eau.
                                Sa mission est « de promouvoir la sensibilisation, de construire l'engagement politique et de déclencher l'action sur les questions critiques de l'eau à tous les niveaux, de faciliter la conservation efficace, la protection, le développement, la planification, la gestion et
                                l'utilisation de l'eau dans toutes ses dimensions sur une base écologiquement durable au profit de toute vie sur Terre ». Fondé en 1996 avec son siège permanent dans la ville française de Marseille, le Conseil Mondial de l'Eau
                                est une organisation plateforme internationale multi-parties prenantes rassemblant près de 400 institutions de tous horizons, de près de 70 pays à travers le monde. En fournissant une plateforme pour encourager les débats et les échanges d'expériences,
                                le Conseil Mondial de l'Eau vise à atteindre une vision stratégique commune sur la gestion des ressources en eau et des services d'eau parmi toutes les parties prenantes de la communauté de l'eau. Dans le processus, le Conseil catalyse également les initiatives et activités,
                                dont les résultats convergent vers son produit phare, le Forum Mondial de l'Eau. Le Forum Mondial de l'Eau contribue au dialogue du processus de prise de décision sur l'eau au niveau mondial, cherchant à atteindre l'utilisation rationnelle et durable de cette ressource.
                                Étant donné sa portée politique, technique et institutionnelle, l'une des principales caractéristiques du Forum est la participation ouverte et démocratique d'acteurs issus de différents secteurs, en faisant un événement de la plus haute importance sur l'agenda international.
                                Le Conseil Mondial de l'Eau organise le Forum tous les trois ans avec le pays et la ville hôtes respectifs. À ce jour, il y a eu sept éditions du Forum Mondial de l'Eau, dans différents pays, sur quatre continents différents.
                                En 2018, le Brésil a accueilli la 8ème édition du Forum Mondial de l'Eau. C'était la première fois que l'événement se tenait dans l'hémisphère sud.
                            </p>
