                            <p>
                                En tant que programme de l'Académie Diplomatique Africaine (ADA), la mission de l'IDA repose sur les principes fondamentaux que chaque association IDA devrait défendre, à savoir le droit de poursuivre la connaissance pour elle-même, de suivre la quête de la vérité où qu'elle mène, la tolérance des opinions divergentes et la liberté de toute ingérence politique.
                            </p>
